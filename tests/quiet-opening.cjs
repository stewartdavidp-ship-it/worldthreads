const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 if(process.env.WORLDTHREADS_KEYBOARD)await require('./keyboard-controls.cjs')(page);
 await page.goto(process.env.WORLDTHREADS_URL||'http://127.0.0.1:8768');
 await page.waitForSelector('[data-start-story]');
 assert((await page.locator('#storyHeading').innerText()).includes('What made crossing the Andes possible?'));
 assert.equal(await page.locator('[data-start-story]').count(),3);
 assert.equal(await page.locator('.story-cover .scene-art, .story-first-art .scene-art').count(),3);
 assert(!(await page.locator('.progress-summary').isVisible()));
 assert(!(await page.locator('.expedition-meter').isVisible()));
 assert(!(await page.locator('.earned-badges').isVisible()));
 await page.screenshot({path:'../../outputs/WorldThreads quieter opening.png',fullPage:true});
 await page.locator('.expedition-goal>details>summary').click();
 assert(await page.locator('.expedition-meter').isVisible());
 await page.click('[data-open-journey]');await page.locator('#investigationProgress summary').click();
 assert(await page.locator('.earned-badges').isVisible());
 await page.locator('#investigationProgress summary').click();await page.click('[data-close-journey]');
 await page.click('[data-start-story=relief]');
 assert(!(await page.locator('.progress-summary').isVisible()));
 assert(await page.locator('[data-case-clue]').first().isVisible());
 assert.equal(await page.locator('.visual-record .record-icon').count(),3);
 assert(!(await page.locator('.story-stop').first().isVisible()));
 await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
 await page.screenshot({path:'../../outputs/WorldThreads first investigation.png',fullPage:true});
 await page.locator('.story-route>summary').click();
 assert(await page.locator('.story-stop').first().isVisible());
 assert(await page.locator('[data-story-frontier]').isDisabled());
 await page.click('#storyMode');
 assert((await page.locator('[data-start-story=relief]').innerText()).includes('Resume'));
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'../../outputs/WorldThreads quieter opening mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:900});
 await page.goto(new URL('?story=1816',page.url()).href);
 await page.locator('.story-1816-comparison summary').click();
 const panels=await page.locator('.region-comparison section').evaluateAll(es=>es.map(e=>({x:e.getBoundingClientRect().x,y:e.getBoundingClientRect().y})));
 assert(panels[1].x>panels[0].x && Math.abs(panels[0].y-panels[1].y)<2,'Desktop crop reports align for comparison');
 await page.locator('.story-1816-comparison summary').click();
 await page.waitForFunction(()=>history.state?.comparisonOpen===false);
 await page.setViewportSize({width:390,height:664});
 await page.goto(new URL('?story=1816',page.url()).href);
 await page.locator('.story-1816').waitFor();
 assert.match(await page.locator('.story-1816').innerText(),/Mount Tambora erupted in April 1815/);
 const comparison=page.locator('.story-1816-comparison');
 const invitation=await comparison.locator('summary').boundingBox();
 assert(invitation && invitation.y+invitation.height<=664,'Homework next step is in the initial phone viewport');
 const feedback=page.locator('footer .wt-feedback-launch');
 await feedback.waitFor();
 assert.equal(await feedback.evaluate(el=>getComputedStyle(el).position),'static');
 const feedbackBox=await feedback.boundingBox();
 assert(feedbackBox.y>=invitation.y+invitation.height,'Feedback is below the comparison control');
 assert.equal(await comparison.evaluate(el=>el.open),false);
 await comparison.locator('summary').click();
 assert.match(await comparison.innerText(),/bumper rice crop/);
 await comparison.getByRole('link',{name:'Try the guided investigation'}).click();
 await page.locator('.harvest-ai').waitFor();
 await page.goBack();
 await page.locator('.story-1816-comparison[open]').waitFor();
 await page.click('#researchMode');
 await page.goBack();
 await page.locator('.story-1816-comparison[open]').waitFor();
 await page.goto(new URL('./',page.url()).href);
 const start=await page.getByRole('button',{name:'Start the Andes story'}).boundingBox();
 assert(start && start.y+start.height<=664,'The featured story starts in the initial phone viewport');
 await page.getByRole('button',{name:'Start the Andes story'}).click();
 const scene=page.locator('.story-scene');
 const narrative=await scene.locator('.story-narrative').first().boundingBox();
 assert(narrative && narrative.y<664,'The Andes opening starts in the initial phone viewport');
 for (const selector of ['#storyCaseReadiness','.story-method','#investigationProgress']) {
  assert(await page.locator(selector).evaluate(el=>!!el.closest('#journeyPanel')));
 }
 const andesNext=scene.getByRole('button',{name:'How did they prepare the army?'});
 assert(await andesNext.evaluate(el=>el.closest('.story-actions').previousElementSibling.matches('.story-narrative')));
 await andesNext.click();
 assert.match(await page.locator('#storyHeading').innerText(),/Equipment needs an organized army/);
 await feedback.click();
 await page.getByRole('dialog',{name:'Share feedback'}).waitFor();
 await page.keyboard.press('Escape');
 await browser.close();
 console.log('PASS: story-first home and sourced 1816 entry fit the first phone viewport; comparison and guided handoff work; goals and badges expand; active progress, evidence clues, resume and mobile reflow remain accessible.');
})().catch(e=>{console.error(e);process.exit(1)});
